#!/bin/sh

set -eu

backup_dir="${BACKUP_DIR:-/backups}"
interval_seconds="${BACKUP_INTERVAL_SECONDS:-86400}"
retention_days="${BACKUP_RETENTION_DAYS:-14}"
retention_count="${BACKUP_RETENTION_COUNT:-2}"
exclude_table_data="${BACKUP_EXCLUDE_TABLE_DATA:-tushare_raw_record}"
compression="${BACKUP_COMPRESSION:-zstd:1}"
last_success="${backup_dir}/.last-success"
archive_pattern="claw-quant-[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]-[0-9][0-9][0-9][0-9][0-9][0-9].dump"
# pg_dump shares the host filesystem with Docker Desktop on the default install.
reserve_kib="${BACKUP_FREE_RESERVE_KIB:-5242880}"

available_kib() {
    df -Pk "${backup_dir}" | awk 'NR==2 {print $4}'
}

for value in "${interval_seconds}" "${retention_days}" "${retention_count}" "${reserve_kib}"; do
    case "${value}" in ''|*[!0-9]*) printf 'invalid backup configuration\n' >&2; exit 1 ;; esac
done
[ "${interval_seconds}" -gt 0 ] && [ "${retention_count}" -ge 2 ] || {
    printf 'backup policy must preserve at least two valid archives\n' >&2; exit 1;
}
mkdir -p "${backup_dir}"

dump_pid=""
partial=""
checksum_partial=""
cleanup() {
    if [ -n "${dump_pid}" ]; then
        kill "${dump_pid}" 2>/dev/null || true
        wait "${dump_pid}" 2>/dev/null || true
    fi
    [ -z "${partial}" ] || rm -f "${partial}"
    [ -z "${checksum_partial}" ] || rm -f "${checksum_partial}"
}
trap cleanup EXIT
trap 'exit 143' TERM INT

prune_backups() {
    # OS lock is released even after process death; prevent two large hash scans
    # and competing rotations when maintenance overlaps the daily backup.
    if command -v flock >/dev/null 2>&1; then
        exec 9>"${backup_dir}/.retention.lock"
        flock -n 9 || return 0
    fi
    backup_count=0
    # Backup file names are generated by this script and contain no spaces.
    for backup_file in $(find "${backup_dir}" -maxdepth 1 -type f \
        -name "${archive_pattern}" -print | sort -r); do
        # Count only completed, readable archives with a checksum sidecar.
        [ -s "${backup_file}.sha256" ] || continue
        pg_restore --list "${backup_file}" >/dev/null 2>&1 || continue
        if [ "${backup_count}" -lt "${retention_count}" ] && [ "${backup_file}" != "${1:-}" ]; then
            if ! (cd "${backup_dir}" && sha256sum -c "$(basename "${backup_file}").sha256" >/dev/null 2>&1); then
                printf 'backup retention skipped invalid checksum: %s\n' "${backup_file}" >&2
                continue
            fi
        fi
        backup_count=$((backup_count + 1))
        if [ "${backup_count}" -gt "${retention_count}" ]; then
            rm -f "${backup_file}" "${backup_file}.sha256"
        elif [ "${backup_count}" -gt 2 ] && find "${backup_file}" \
            -mtime "+${retention_days}" -print -quit | grep -q .; then
            # Never remove the newest completed snapshot merely because a
            # host was offline longer than the retention window.
            rm -f "${backup_file}" "${backup_file}.sha256"
        fi
    done
    if command -v flock >/dev/null 2>&1; then flock -u 9; fi
}

# Explicit maintenance never touches partial dumps or unrelated/manual backups.
if [ "${1:-}" = "--prune-only" ]; then
    prune_backups
    exit 0
fi

write_heartbeat() {
    heartbeat_success=0
    if [ -s "${last_success}" ]; then
        heartbeat_success="$(cat "${last_success}")"
    fi
    backup_instance="$(hostname | tr -cd 'A-Za-z0-9_.-')"
    psql -v ON_ERROR_STOP=1 \
        -c "INSERT INTO sys_service_heartbeat(
                component,instance_id,process_id,last_seen_at,details
            ) VALUES (
                'backup', '${backup_instance}', $$, NOW(),
                jsonb_build_object(
                    'backup_dir','/backups',
                    'last_success_epoch',${heartbeat_success},
                    'interval_seconds',${interval_seconds},
                    'retention_days',${retention_days},
                    'retention_count',${retention_count},
                    'excluded_table_data','${exclude_table_data}',
                    'compression','${compression}',
                    'operation',${1:-'idle'}
                )
            ) ON CONFLICT(component,instance_id) DO UPDATE SET
                process_id=EXCLUDED.process_id,
                last_seen_at=EXCLUDED.last_seen_at,
                details=EXCLUDED.details" >/dev/null || true
}

# Preserve the install/upgrade backup as the first valid daily snapshot rather
# than creating a second large dump immediately when the sidecar is introduced.
if [ ! -s "${last_success}" ]; then
    for existing in $(find "${backup_dir}" -maxdepth 1 -type f -name "${archive_pattern}" -mmin -1440 | sort -r); do
        [ -s "${existing}.sha256" ] || continue
        pg_restore --list "${existing}" >/dev/null 2>&1 || continue
        (cd "${backup_dir}" && sha256sum -c "$(basename "${existing}").sha256" >/dev/null 2>&1) || continue
        existing_epoch=$(stat -c %Y "${existing}" 2>/dev/null || stat -f %m "${existing}")
        printf '%s\n' "${existing_epoch}" > "${last_success}.partial"
        mv "${last_success}.partial" "${last_success}"
        break
    done
fi

while true; do
    now="$(date +%s)"
    previous=0
    if [ -s "${last_success}" ]; then
        previous="$(cat "${last_success}")"
    fi
    if [ $((now - previous)) -ge "${interval_seconds}" ]; then
        # Prune only after the new archive and checksum have been published.
        latest=$(find "${backup_dir}" -maxdepth 1 -type f -name "${archive_pattern}" | sort -r | head -1)
        expected_kib=0
        if [ -n "${latest}" ]; then
            latest_bytes=$(stat -c %s "${latest}" 2>/dev/null || stat -f %z "${latest}")
            expected_kib=$(( (latest_bytes + 1023) / 1024 ))
        fi
        if [ "$(available_kib)" -lt $((expected_kib + reserve_kib)) ]; then
            printf 'backup deferred: available=%s KiB, previous dump=%s KiB, reserve=%s KiB\n' \
                "$(available_kib)" "${expected_kib}" "${reserve_kib}" >&2
            write_heartbeat "'waiting_for_disk_space'"
            sleep 60
            continue
        fi
        stamp="$(date +%Y%m%d-%H%M%S)"
        target="${backup_dir}/claw-quant-${stamp}.dump"
        partial="${target}.partial"
        checksum_partial="${target}.sha256.partial"
        rm -f "${partial}" "${checksum_partial}"
        pg_dump --format=custom --no-owner --no-acl \
            --compress="${compression}" \
            --exclude-table-data="${exclude_table_data}" \
            --file="${partial}" "${PGDATABASE}" &
        dump_pid=$!
        while kill -0 "${dump_pid}" 2>/dev/null; do
            if [ "$(available_kib)" -le "${reserve_kib}" ]; then
                printf 'backup interrupted: destination reached free space reserve\n' >&2
                kill "${dump_pid}" 2>/dev/null || true
                break
            fi
            write_heartbeat "'dumping'"
            sleep 30
        done
        if wait "${dump_pid}" && [ -s "${partial}" ] \
            && pg_restore --list "${partial}" >/dev/null; then
            dump_pid=""
            digest=$(sha256sum "${partial}")
            printf '%s  %s\n' "${digest%% *}" "$(basename "${target}")" > "${checksum_partial}"
            mv "${partial}" "${target}"
            mv "${checksum_partial}" "${target}.sha256"
            date +%s > "${last_success}.partial"
            mv "${last_success}.partial" "${last_success}"
            prune_backups "${target}"
            printf 'backup completed: %s\n' "${target}"
        else
            dump_pid=""
            rm -f "${partial}" "${checksum_partial}"
            printf 'backup failed at %s\n' "$(date -Iseconds)" >&2
        fi
    fi
    dump_pid=""
    write_heartbeat "'idle'"
    sleep 60
done
